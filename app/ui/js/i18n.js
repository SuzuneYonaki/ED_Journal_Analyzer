let currentLang = localStorage.getItem("ed_lang") || "ja";

function t(key) {
  if (i18n[currentLang] && i18n[currentLang][key]) {
    return i18n[currentLang][key];
  }
  return i18n.ja[key] || key;
}

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem("ed_lang", lang);
  updateStaticTexts();
}
